// Writes packages/server/supabase/src/database-types/database.types.ts from a
// database built from supabase/migrations. Run with `pnpm db:types`; CI runs it
// on a fresh local database and fails if the committed file differs.
//
// The output depends only on the migrations and two pinned tools: the Supabase
// CLI (root devDependency) generates, and the repository's Prettier formats.
// The hosted project is never read, so no credentials are needed, and
// `__InternalSupabase.PostgrestVersion` is not written: it describes where the
// schema is deployed, not the schema (see the server-supabase README).
//
// The database comes from `--db-url`, or SUPABASE_DB_URL, or else the local stack
// that `pnpm exec supabase db start` runs (port and password from
// supabase/config.toml defaults). Any Postgres the migrations were applied to
// works, as long as it is on 127.0.0.1 or localhost: a hosted target is refused
// before the CLI starts. The reviewed exception is
// `--allow-remote-target <project-ref>`, whose ref must equal the one in the URL.
//
// `--stack` reads this worktree's disposable stack (`pnpm db:stack start`), the
// database a slice's migrations are checked on, instead of the shared default.
//
// Usage: pnpm db:types [--db-url <url> | --stack] [--allow-remote-target <project-ref>]
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import { status as isolatedStackStatus } from './db-test-stack.mjs';
import {
  assertLocalTarget,
  flagValue,
  redactUrl,
  TargetRefusedError,
} from './lib/loopback.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(
  root,
  'packages/server/supabase/src/database-types/database.types.ts',
);
const argv = process.argv.slice(2);
function stackDbUrl() {
  if (!argv.includes('--stack')) return undefined;
  const stack = isolatedStackStatus();
  if (!stack) {
    process.stderr.write(
      'db:types: --stack needs a running stack (start one with `pnpm db:stack start`).\n',
    );
    process.exit(1);
  }
  // The local database does not offer TLS, and the CLI asks for it by default.
  const url = new URL(stack.dbUrl);
  url.searchParams.set('sslmode', 'disable');
  return url.toString();
}
const dbUrl =
  flagValue(argv, 'db-url') ??
  stackDbUrl() ??
  process.env.SUPABASE_DB_URL ??
  'postgresql://postgres:postgres@127.0.0.1:54322/postgres?sslmode=disable';

try {
  const { remote, ref } = assertLocalTarget(dbUrl, {
    allowRemoteTarget: flagValue(argv, 'allow-remote-target'),
  });
  if (remote) {
    process.stderr.write(
      `db:types: reading the REMOTE project ${ref} (${redactUrl(dbUrl)})\n`,
    );
  }
} catch (error) {
  if (!(error instanceof TargetRefusedError)) throw error;
  process.stderr.write(`db:types: ${error.message}\n`);
  process.exit(1);
}

const HEADER = `// Generated by \`pnpm db:types\` from supabase/migrations. Do not edit by hand.\n\n`;

let generated;
try {
  generated = execFileSync(
    'supabase',
    ['gen', 'types', 'typescript', '--db-url', dbUrl, '--schema', 'public'],
    { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] },
  );
} catch (error) {
  // The CLI's own message says what failed (no database, a failed connection).
  process.stderr.write(error.stderr ?? String(error));
  process.exit(1);
}
if (!generated.includes('export type Database')) {
  process.stderr.write('db:types: the CLI returned no Database type\n');
  process.exit(1);
}

const options = (await prettier.resolveConfig(target)) ?? {};
const formatted = await prettier.format(HEADER + generated, {
  ...options,
  filepath: target,
});
// Written only after generation and formatting succeed, so a failure never
// leaves an empty or half-written file behind.
writeFileSync(target, formatted);
console.log(`db:types: wrote ${target.slice(root.length + 1)}`);
